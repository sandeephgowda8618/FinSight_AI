BEGIN;

-- Authentication/security audit trail.
-- workspace_id remains nullable because the current application schema
-- does not yet contain the workspaces table.
CREATE TABLE audit_events (
    audit_event_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id UUID NULL,
    actor_user_id UUID NULL REFERENCES users(user_id) ON DELETE SET NULL,
    action_key VARCHAR(120) NOT NULL,
    resource_type VARCHAR(80) NOT NULL,
    resource_id UUID NULL,
    outcome VARCHAR(20) NOT NULL
        CHECK (outcome IN ('success', 'failure', 'denied')),
    correlation_id UUID NULL,
    details_redacted JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_events_occurred_at
    ON audit_events (occurred_at DESC);

CREATE INDEX idx_audit_events_actor_occurred
    ON audit_events (actor_user_id, occurred_at DESC);

CREATE INDEX idx_audit_events_action_occurred
    ON audit_events (action_key, occurred_at DESC);

-- Persistent, shared login-failure counters.
-- key_hash must be a keyed digest generated by the application;
-- raw email addresses, IP addresses, passwords and tokens do not belong here.
CREATE TABLE auth_login_throttle (
    scope_type VARCHAR(16) NOT NULL
        CHECK (scope_type IN ('account', 'ip')),
    key_hash CHAR(64) NOT NULL,
    failed_attempts INTEGER NOT NULL DEFAULT 0
        CHECK (failed_attempts >= 0),
    window_started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    blocked_until TIMESTAMPTZ NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (scope_type, key_hash)
);

CREATE INDEX idx_auth_login_throttle_blocked_until
    ON auth_login_throttle (blocked_until)
    WHERE blocked_until IS NOT NULL;

COMMIT;
